/** @type {NutritionRegion[]} */
export const nutritionRegions = regionCatalog.map((region) => ({
  ...region,
  coverage: regionCoverage[region.id] ?? [{ lat: region.lat, lng: region.lng }],
}));

export function getRegionById(regionId) {
  return nutritionRegions.find((region) => region.id === regionId) ?? nutritionRegions[0];
}
